#!/bin/bash

# ==============================================================================
# Скрипт для конвертации EPUB в PDF-буклет (A4, тетради по 16 страниц/4 листа)
# ==============================================================================
# Зависимости для Arch Linux:
# sudo pacman -S pandoc-cli typst texlive-binextra
# ==============================================================================

# --- ОСНОВНЫЕ ПЕРЕМЕННЫЕ (Редактировать под каждую книгу) ---

INPUT_FILE="${1:-input.epub}"           # Входной файл (по умолчанию input.epub, можно передать 1-м аргументом)
OUTPUT_FILE="${2:-booklet.pdf}"         # Выходной файл (по умолчанию booklet.pdf, 2-й аргумент)

# Параметры страницы исходного текста (А5 - ровно половина А4)
PAGE_SIZE="a5"

# Отступы (минимальные). 5mm - это безопасный минимум, 
# так как большинство принтеров имеют "слепую зону" ~3-5mm.
MARGIN_LEFT="1mm"
MARGIN_RIGHT="1mm"
MARGIN_TOP="1mm"
MARGIN_BOTTOM="1mm"

# Параметры шрифта текста
FONT_SIZE="11pt"
# Рекомендуется использовать шрифты, доступные в вашей системе и поддерживающие кириллицу.
# Примеры: "Liberation Serif", "Linux Libertine", "DejaVu Serif"
MAIN_FONT="Liberation Serif" 

# Параметры сборки буклета
# 16 страниц в тетради (это 4 физических листа А4 с двусторонней печатью)
SIGNATURE_SIZE=16 

# Временный файл (промежуточный PDF формата А5 перед раскладкой)
TEMP_PDF="temp_a5_intermediate.pdf"

# -----------------------------------------------------------
# ЛОГИКА СКРИПТА
# -----------------------------------------------------------

if [ ! -f "$INPUT_FILE" ]; then
    echo "❌ Ошибка: Файл '$INPUT_FILE' не найден."
    echo "Использование: $0 [входной_файл.epub] [выходной_файл.pdf]"
    exit 1
fi

echo "📖 Шаг 1: Конвертация EPUB в PDF (A5) с использованием Pandoc и Typst..."
pandoc "$INPUT_FILE" \
    -o "$TEMP_PDF" \
    --pdf-engine=typst \
    -V papersize="$PAGE_SIZE" \
    -V margin.left="$MARGIN_LEFT" \
    -V margin.right="$MARGIN_RIGHT" \
    -V margin.top="$MARGIN_TOP" \
    -V margin.bottom="$MARGIN_BOTTOM" \
    -V fontsize="$FONT_SIZE" \
    -V mainfont="$MAIN_FONT"

if [ $? -ne 0 ] || [ ! -f "$TEMP_PDF" ]; then
    echo "❌ Ошибка при конвертации файла с помощью Pandoc."
    exit 1
fi

echo "🖨️  Шаг 2: Сборка буклета формата А4 (тетради по $SIGNATURE_SIZE стр.) с помощью pdfjam..."
# pdfjam автоматически переводит страницы в ландшафтную ориентацию и распределяет их так,
# чтобы при складывании пополам получилась книжка.
pdfjam "$TEMP_PDF" \
    --booklet 'true' \
    --landscape \
    --signature "$SIGNATURE_SIZE" \
    --outfile "$OUTPUT_FILE"

if [ $? -ne 0 ]; then
    echo "❌ Ошибка при создании буклета с помощью pdfjam."
    rm -f "$TEMP_PDF"
    exit 1
fi

echo "🧹 Шаг 3: Очистка временных файлов..."
rm -f "$TEMP_PDF"

echo "========================================================================="
echo "✅ Готово! Результат сохранен в: $OUTPUT_FILE"
echo "========================================================================="
echo "ВАЖНО: Инструкция для печати"
echo "1. Откройте '$OUTPUT_FILE' в вашем PDF-ридере."
echo "2. В настройках печати принтера выберите формат А4 и альбомную ориентацию (Landscape)."
echo "3. Обязательно включите двустороннюю печать по КОРОТКОМУ КРАЮ (Short Edge / Flip on short edge)."
echo "   (Именно этот параметр заставляет страницы правильно переворачиваться как в книге)."
echo "========================================================================="

